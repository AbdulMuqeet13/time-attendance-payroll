|--------------------------------------------------------------------------
| Functions
|--------------------------------------------------------------------------
|
| While Pest is very powerful out-of-the-box, you may have some testing code specific to your
| project that you don't want to repeat in every file. Here you can also expose helpers as
| global functions to help you to reduce the number of lines of code in your test files.
|
*/

/**
 * A user holding the given role. Pass a branch id to tie the user to one branch.
 *
 * @param  array<string, mixed>  $attributes
 */
function userWithRole(RoleEnum $role, array $attributes = []): User
{
    return User::factory()->create($attributes)->assignRole($role->value);
}

/**
 * Send a raw text body the way a ZKTeco device does.
 */
function devicePost(string $uri, string $body): TestResponse
{
    return test()->call('POST', $uri, [], [], [], ['CONTENT_TYPE' => 'text/plain'], $body);
}
